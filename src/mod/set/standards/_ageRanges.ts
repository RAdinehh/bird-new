/**
 * پیدا کردن الگو بر اساس نژاد
 */
export function getRangePattern(
  birdKind: string | undefined,
  purposes: string[] | undefined,
  key: string,
): SpeciesRanges | null {
  // اگه گوشتی
  if (purposes?.includes('broiler')) {
    if (birdKind === 'chicken') return AGE_RANGE_PATTERNS['chicken-broiler'];
    if (birdKind === 'turkey') return AGE_RANGE_PATTERNS['turkey-broiler'];
    if (birdKind === 'duck') return AGE_RANGE_PATTERNS['duck-broiler'];
    if (birdKind === 'goose') return AGE_RANGE_PATTERNS['goose-broiler'];
    if (birdKind === 'quail') return AGE_RANGE_PATTERNS['quail-broiler'];
  }
  // اگه تخم‌گذار
  if (purposes?.includes('layer')) {
    if (birdKind === 'chicken') return AGE_RANGE_PATTERNS['chicken-layer'];
    if (birdKind === 'quail') return AGE_RANGE_PATTERNS['quail-layer'];
  }
  // اگه دو منظوره
  if (purposes?.includes('dual')) {
    if (birdKind === 'chicken') return AGE_RANGE_PATTERNS['chicken-dual'];
    if (birdKind === 'duck') return AGE_RANGE_PATTERNS['duck-dual'];
    if (birdKind === 'goose') return AGE_RANGE_PATTERNS['goose-dual'];
  }
  // اگه تزئینی
  if (purposes?.includes('ornamental') && birdKind === 'chicken') {
    return AGE_RANGE_PATTERNS['chicken-ornamental'];
  }
  return null;
}
